#!/usr/bin/env python3
"""Generate runner integration files from prompts/ (the single source of truth).

    python scripts/build.py          # write files
    python scripts/build.py --check  # exit 1 if generated files are stale (used in tests/CI)

Outputs
  skills/research/SKILL.md            Claude Code skill (model-invoked orchestrator)
  agents/<role>.md                    Claude Code subagents (plugin-scoped as gauntlet:<role>)
  integrations/opencode/...           opencode agents + command + opencode.json
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from gauntlet.config import DEFAULT_MODELS, ROLE_TIERS  # noqa: E402

PROMPTS = ROOT / "prompts"
ROLES = [r for r in ROLE_TIERS if r != "orchestrator"]
GENERATED = "<!-- Generated by scripts/build.py from prompts/. Edit the source, then rebuild. -->"

SKILL_DESCRIPTION = (
    "Research a question with sources and checked claims. Use when the user asks what the evidence says, "
    "whether something is true, for a literature review, or to research, investigate or compare findings on a "
    "topic in any field. Produces a report where every claim carries a label showing how it was checked "
    "(quoted sources, tests on held-out data, independent replication) and new ideas are labelled tested, "
    "refuted or untested."
)


def front(text: str) -> tuple[dict[str, str], str]:
    m = re.match(r"---\s*\n(.*?)\n---\s*\n", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def alias(model: str) -> str:
    for fam in ("opus", "sonnet", "haiku", "fable"):
        if model.startswith(f"claude-{fam}"):
            return fam
    return model


def outputs() -> dict[Path, str]:
    rules = (PROMPTS / "rules.md").read_text().strip()
    orch = (PROMPTS / "orchestrator.md").read_text().strip()
    out: dict[Path, str] = {}

    out[ROOT / "skills/research/SKILL.md"] = (
        "---\nname: research\n"
        f"description: {SKILL_DESCRIPTION}\n"
        'argument-hint: "<question> [quick|standard|deep]"\n---\n\n'
        f"{GENERATED}\n\n{orch}\n"
    )
    oc_agents = {}
    for role in ROLES:
        meta, body = front((PROMPTS / "roles" / f"{role}.md").read_text())
        model = DEFAULT_MODELS[ROLE_TIERS[role]]
        text = f"{body.strip()}\n\n{rules}\n"
        fm = [f"name: {role}", f"description: {meta['description']}", f"model: {alias(model)}"]
        if meta.get("disallowed"):
            fm.append(f"disallowedTools: {meta['disallowed']}")
        out[ROOT / "agents" / f"{role}.md"] = "---\n" + "\n".join(fm) + f"\n---\n\n{GENERATED}\n\n{text}"
        denied = [t.strip().lower() for t in meta.get("disallowed", "").split(",") if t.strip()]
        oc_tools = {t: False for t in ("write", "edit", "bash") if t in denied}
        ofm = [f"description: {meta['description']}", "mode: subagent", f"model: anthropic/{model}"]
        if oc_tools:
            ofm.append("tools:\n" + "\n".join(f"  {k}: false" for k in oc_tools))
        out[ROOT / f"integrations/opencode/.opencode/agent/gauntlet-{role}.md"] = (
            "---\n" + "\n".join(ofm) + f"\n---\n\n{GENERATED}\n\n{text}")
        oc_agents[role] = True
    oc_orch = re.sub(r"`gauntlet:(\w+)`", r"`gauntlet-\1`", orch).replace("the Agent tool", "the task tool")
    out[ROOT / "integrations/opencode/.opencode/command/research.md"] = (
        "---\ndescription: Research a question with Gauntlet (every claim shows how it was checked)\n"
        f"model: anthropic/{DEFAULT_MODELS['strong']}\n---\n\n{GENERATED}\n\n{oc_orch}\n")
    out[ROOT / "integrations/opencode/opencode.json"] = json.dumps({
        "$schema": "https://opencode.ai/config.json",
        "mcp": {"gauntlet": {"type": "local", "enabled": True,
                             "command": ["python3", "/path/to/gauntlet/runtime/mcp_server.py"]}},
    }, indent=2) + "\n"
    return out


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        if path.exists() and path.read_text() == text:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check and stale:
        print("stale generated files (run python scripts/build.py):\n  " + "\n  ".join(map(str, stale)))
        return 1
    for p in stale:
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
